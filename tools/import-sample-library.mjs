/**
 * P2 — Sample library ingest pipeline: converts a folder of WAV multisamples
 * (free CC-licensed libraries: Salamander Grand Piano, VSCO 2 Community
 * Edition, University of Iowa samples, or any library following the naming
 * convention) into a WILSONIX multisample bank:
 *
 *   public/banks/<bankId>/*.flac          — FLAC (lossless, verified bit-identical)
 *   src/audio/multisample-manifest.js     — bank registry (rewritten deterministically)
 *
 * Filename convention (case-insensitive):
 *   {Note}[{s|b|#}][{octave}][_?v{N}][_?rr{N}].wav
 *     C4v5.wav        → note C4 (midi 60), velocity layer 5
 *     C4_v5_rr2.wav   → velocity layer 5, round-robin variant 2
 *     Fs4v2.wav       → F#4, velocity layer 2
 *     Gb2v1.wav       → Gb2, velocity layer 1
 *     A0.wav          → note A0, velocity layer 1 (single layer)
 *   Drum-kit / percussion banks additionally accept a raw MIDI number form
 *   (needed for keys 0-11 which have no note name, e.g. RX7 snares 1-9):
 *     N36.wav         → midi 36 (kick), single layer
 *     N5_v2.wav       → midi 5, velocity layer 2
 *
 * Velocity thresholds default to an even 1-127 distribution across the
 * detected layer count; pass an explicit comma-separated list to override:
 *   node tools/import-sample-library.mjs ./library salamander_c5 "Salamander Grand (Yamaha C5)" "Acoustic Piano" 1,46,76,96,101,112
 *
 * Usage: node tools/import-sample-library.mjs <libraryDir> <bankId> <name> <category> [thresholds]
 * Idempotent: already-FLACed files are skipped; the manifest is rewritten.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join, resolve } from "node:path";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const PUBLIC = join(ROOT, "public");
const MANIFEST_PATH = join(ROOT, "src", "audio", "multisample-manifest.js");
const MANIFEST_HEADER = `/**
 * WILSONIX MIDIKEY - Imported Multisample Bank Registry.
 *
 * GENERATED by tools/import-sample-library.mjs — do not hand-edit; changes are
 * overwritten on the next import. Each entry is one keyed multisample
 * instrument: velocity layers (vl1..vlN with per-bank thresholds), round-robins
 * (rr1..rrN cycled per note), and lossless FLAC samples.
 */

export const MULTISAMPLE_BANKS = `;

const SEMITONE = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };

function noteToMidi(letter, accidental, octave) {
  let semi = SEMITONE[letter.toUpperCase()];
  if (semi === undefined) return null;
  if (accidental === "#" || accidental === "s" || accidental === "S") semi += 1;
  else if (accidental === "b" || accidental === "B") semi -= 1;
  const midi = (octave + 1) * 12 + semi;
  return midi >= 0 && midi <= 127 ? midi : null;
}

function parseSampleName(filename) {
  const base = filename.replace(/\.(wav|wave)$/i, "");
  let match = base.match(/^([A-Ga-g])([sb#]?)(\d{1,2})(?:_?v(\d+))?(?:_?rr(\d+))?$/);
  if (match) {
    const midi = noteToMidi(match[1], match[2], parseInt(match[3], 10));
    if (midi === null) return null;
    return {
      m: midi,
      vl: match[4] ? parseInt(match[4], 10) : 1,
      rr: match[5] ? parseInt(match[5], 10) : 0,
    };
  }
  // Raw MIDI number form: N36.wav → midi 36 (drum-kit keys below C0)
  match = base.match(/^N(\d{1,3})(?:_?v(\d+))?(?:_?rr(\d+))?$/i);
  if (match) {
    const midi = parseInt(match[1], 10);
    if (!(midi >= 0 && midi <= 127)) return null;
    return {
      m: midi,
      vl: match[2] ? parseInt(match[2], 10) : 1,
      rr: match[3] ? parseInt(match[3], 10) : 0,
    };
  }
  return null;
}

function rawHash(path) {
  // Decode to packed s24le raw and hash — equal hashes == bit-identical audio
  // (same verification ground rule as transcode-sample-assets.mjs).
  const raw = execFileSync(
    "ffmpeg",
    ["-v", "error", "-i", path, "-f", "s24le", "-acodec", "pcm_s24le", "-"],
    { encoding: null, maxBuffer: 1 << 30 },
  );
  return createHash("sha256").update(raw).digest("hex");
}

function transcodeToFlac(file, outFile) {
  try {
    execFileSync(
      "ffmpeg",
      ["-v", "error", "-y", "-i", file, "-map", "0:a:0", "-c:a", "flac", "-compression_level", "12", outFile],
      { stdio: "ignore" },
    );
  } catch (err) {
    console.error(`FAILED transcode: ${file}\n${err}`);
    rmSync(outFile, { force: true });
    return false;
  }
  try {
    if (rawHash(file) !== rawHash(outFile)) {
      console.error(`INTEGRITY MISMATCH (decoded PCM differs): ${file}`);
      rmSync(outFile, { force: true });
      return false;
    }
  } catch (err) {
    console.error(`FAILED integrity verification: ${file}\n${err}`);
    rmSync(outFile, { force: true });
    return false;
  }
  return true;
}

/**
 * Rewrites src/audio/multisample-manifest.js deterministically: existing
 * entries are preserved (parsed from the generated JSON body), the imported
 * bank is added/updated.
 */
function readExistingBanks() {
  if (!existsSync(MANIFEST_PATH)) return {};
  try {
    const text = readFileSync(MANIFEST_PATH, "utf8");
    const start = text.indexOf("MULTISAMPLE_BANKS = {");
    if (start < 0) return {};
    const objStart = text.indexOf("{", start);
    const end = text.lastIndexOf("};");
    if (objStart < 0 || end <= objStart) return {};
    const json = text.slice(objStart, end + 1).replace(/,(\s*})/g, "$1");
    return JSON.parse(json) || {};
  } catch (err) {
    console.warn(`warn: could not parse existing manifest (${err.message}) — starting fresh`);
    return {};
  }
}

function writeBanks(banks) {
  writeFileSync(MANIFEST_PATH, MANIFEST_HEADER + JSON.stringify(banks, null, 2) + ";\n");
}

// ── CLI ────────────────────────────────────────────────────────────────────
const [libraryDir, bankId, name, category, thresholdsArg] = process.argv.slice(2);
if (!libraryDir || !bankId || !name || !category) {
  console.error(
    "Usage: node tools/import-sample-library.mjs <libraryDir> <bankId> <name> <category> [velocityThresholds]\n" +
      "  e.g. node tools/import-sample-library.mjs ./salamander salamander_c5 \"Salamander Grand (Yamaha C5)\" \"Acoustic Piano\" 1,46,76,96,101,112",
  );
  process.exit(1);
}

const srcDir = resolve(ROOT, libraryDir);
if (!existsSync(srcDir)) {
  console.error(`library dir not found: ${srcDir}`);
  process.exit(1);
}

const outDir = join(PUBLIC, "banks", bankId);
mkdirSync(outDir, { recursive: true });

// 1) Scan + parse the library.
const parsed = [];
const unparsed = [];
for (const entry of readdirSync(srcDir, { withFileTypes: true })) {
  if (!entry.isFile() || !/\.wav$/i.test(entry.name)) continue;
  const info = parseSampleName(entry.name);
  if (info) parsed.push({ file: entry.name, ...info });
  else unparsed.push(entry.name);
}

if (parsed.length === 0) {
  console.error(
    `FAILED: zero WAV files matched the naming convention in ${srcDir}\n` +
      `Expected: {Note}[{s|b|#}][{octave}][_?v{N}][_?rr{N}].wav  e.g. C4v5.wav, C4_v5_rr2.wav\n` +
      (unparsed.length ? `Unmatched names (first 10): ${unparsed.slice(0, 10).join(", ")}` : ""),
  );
  process.exit(1);
}
if (unparsed.length > 0) {
  console.warn(`warn: ${unparsed.length} WAV files did not match the convention and were skipped (e.g. ${unparsed.slice(0, 5).join(", ")})`);
}

// 2) Transcode each sample to FLAC with integrity verification.
const samples = [];
let converted = 0;
let reused = 0;
for (const p of parsed) {
  const outFile = p.file.replace(/\.(wav|wave)$/i, "") + ".flac";
  const outFull = join(outDir, outFile);
  const srcFull = join(srcDir, p.file);

  if (existsSync(outFull)) {
    reused++;
  } else if (transcodeToFlac(srcFull, outFull)) {
    converted++;
  } else {
    continue;
  }
  samples.push({
    f: outFile,
    m: p.m,
    v: `vl${p.vl}`,
    rr: p.rr,
  });
}

if (samples.length === 0) {
  console.error(`FAILED: no samples were produced for ${bankId}`);
  process.exit(1);
}

// 3) Velocity thresholds: explicit arg or even 1-127 distribution.
const vlCount = Math.max(...samples.map((s) => parseInt(s.v.slice(2), 10)));
let velocityThresholds;
if (thresholdsArg) {
  velocityThresholds = thresholdsArg
    .split(",")
    .map((t) => parseInt(t.trim(), 10))
    .filter((t) => Number.isFinite(t) && t >= 1 && t <= 127)
    .sort((a, b) => a - b);
  if (velocityThresholds.length !== vlCount) {
    console.warn(
      `warn: ${velocityThresholds.length} thresholds for ${vlCount} layers — using even distribution instead`,
    );
    velocityThresholds = null;
  }
}
if (!velocityThresholds) {
  velocityThresholds = [];
  for (let i = 0; i < vlCount; i++) {
    velocityThresholds.push(i === 0 ? 1 : Math.round(1 + (i * 126) / vlCount));
  }
}

// 4) Rewrite the registry (preserving existing banks).
const banks = readExistingBanks();
const rrCount = samples.filter((s) => s.rr >= 1).length;
banks[bankId] = {
  id: bankId,
  name,
  category,
  path: `/banks/${bankId}`,
  velocityThresholds,
  sampleCount: samples.length,
  roundRobinCount: rrCount > 0 ? Math.max(...samples.map((s) => s.rr)) : 0,
  samples: samples.sort((a, b) => a.m - b.m || a.v.localeCompare(b.v) || a.rr - b.rr),
};
writeBanks(banks);

console.log(
  `\nP2 ingest summary for "${bankId}": ${samples.length} samples ` +
    `(${converted} converted, ${reused} reused), ${vlCount} velocity layers, ` +
    `${banks[bankId].roundRobinCount} round-robins. Thresholds: [${velocityThresholds.join(", ")}]`,
);
console.log(
  `Instrument "${bankId}" is now in the soundbank catalog — restart the app and it appears in the preset picker.`,
);
