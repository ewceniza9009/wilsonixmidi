/**
 * Regenerates the generated-bank block in src/audio/yamaha-eos-pcm-data.js from
 * the builder manifests in public/banks/yamaha-eos/.
 *
 * The runtime registry must never drift from what tools/sc55-bank-builder.mjs
 * actually rendered, so the bank entries are generated rather than hand-edited.
 * Any hand-written entry that lives OUTSIDE the generated markers is preserved.
 *
 *   node tools/gen-bank-data.mjs
 */
import fs from "node:fs";
import path from "node:path";

const MANIFESTS = ["_sc55-manifest.json", "_juno-manifest.json"];
const DATA = path.join("src", "audio", "yamaha-eos-pcm-data.js");
const START = "  // >>> GENERATED SOUNDFONT BANKS (tools/gen-bank-data.mjs) >>>";
const END = "  // <<< GENERATED SOUNDFONT BANKS <<<";

// The block this tool replaced. It carried its own markers, and the first
// version of this generator only ever appended the new block -- it never
// removed the old one, so every sc55_* key ended up defined twice and eslint
// reported 23 `no-dupe-keys` errors. Strip it on every run so the file
// self-heals instead of needing a one-off manual edit.
const LEGACY_START = "  // >>> SC-55 DERIVED BANKS (generated by tools/sc55-bank-builder.mjs) >>>";
const LEGACY_END = "  // <<< SC-55 DERIVED BANKS <<<";

function stripBlock(text, start, end, label) {
  let out = text;
  let removed = 0;
  for (;;) {
    const s = out.indexOf(start);
    if (s === -1) break;
    const e = out.indexOf(end, s);
    if (e === -1) throw new Error(`${DATA}: found ${label} start marker with no matching end marker`);
    out = out.slice(0, s) + out.slice(e + end.length).replace(/^\r?\n/, "");
    removed++;
  }
  if (removed) {
    // Removing a block leaves the comma that separated it from its neighbour
    // stranded on its own line, which is a syntax error in an object literal.
    out = out.replace(/^[ \t]*,[ \t]*\r?\n(?=[ \t]*\n|[ \t]*\/\/)/gm, "\n");
    console.log(`removed ${removed} stale ${label} block(s)`);
  }
  return out;
}

let block = `${START}\n`;
let total = 0;
for (const file of MANIFESTS) {
  const p = path.join("public", "banks", "yamaha-eos", file);
  if (!fs.existsSync(p)) {
    console.log(`skip ${file} (not built yet)`);
    continue;
  }
  const manifest = JSON.parse(fs.readFileSync(p, "utf8"));
  for (const [id, b] of Object.entries(manifest)) {
    const notes = Object.keys(b.anchors).sort((a, c) => Number(a) - Number(c));
    block += `  ${JSON.stringify(id)}: {\n    id: ${JSON.stringify(id)},\n    name: ${JSON.stringify(b.name)},\n    anchors: {\n`;
    block += notes.map((n) => `      ${JSON.stringify(n)}: ${JSON.stringify(b.anchors[n])},`).join("\n");
    block += `\n    }\n  },\n`;
    total++;
  }
  console.log(`${file}: ${Object.keys(manifest).length} banks`);
}
block += `${END}\n`;

let src = stripBlock(fs.readFileSync(DATA, "utf8"), LEGACY_START, LEGACY_END, "SC-55 derived banks");
const si = src.indexOf(START);
const ei = src.indexOf(END);
if (si === -1 || ei === -1) {
  // No markers yet: insert INSIDE the bank map, preserving everything written
  // by hand, and keep the map comma-separated.
  const close = src.lastIndexOf("};");
  if (close === -1) throw new Error(`${DATA} does not end with the bank map`);
  const head = src.slice(0, close).trimEnd();
  const sep = head.endsWith(",") ? "" : ",";
  src = `${head}${sep}\n${block}${src.slice(close)}`;
} else {
  src = src.slice(0, si) + block + src.slice(ei + END.length + 1);
}

// Match the file's existing line endings instead of forcing LF.
const crlf = fs.readFileSync(DATA).includes(Buffer.from("\r\n"));
fs.writeFileSync(DATA, crlf ? src.replace(/(?<!\r)\n/g, "\r\n") : src);
console.log(`updated ${DATA} with ${total} banks`);
